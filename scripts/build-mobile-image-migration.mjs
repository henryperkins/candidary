/* global URL, process */
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdir, readFile, writeFile, readdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build, version as esbuildVersion } from 'esbuild';

export const BASELINE = 'eceb4053b572562ed00247a7c6469a2599416723';
const root = fileURLToPath(new URL('../', import.meta.url));
const hash = (bytes) => createHash('sha256').update(bytes).digest('hex');

// Compile the actual baseline checkout, without mutating the current checkout or
// committing a duplicate application. CI checks out full history. Dependency
// versions are the unchanged root lockfile; no downloads or runtime overrides.
export async function prepareBaselineApp() {
  const output = resolve(root, 'output/verification/mobile-image-baseline');
  const lockSha256 = hash(await readFile(resolve(root, 'package-lock.json')));
  const builderSha256 = hash(await readFile(fileURLToPath(import.meta.url)));
  try {
    const cached = JSON.parse(await readFile(resolve(output, 'provenance.json'), 'utf8'));
    if (cached.baseline === BASELINE && cached.lockSha256 === lockSha256 && cached.builderSha256 === builderSha256 && cached.esbuildVersion === esbuildVersion
      && cached.bundleSha256 === hash(await readFile(resolve(output, 'baseline-app.mjs')))) return;
  } catch (error) { if (error.code !== 'ENOENT') throw error; }
  const names = execFileSync('git', ['ls-tree', '-r', '--name-only', BASELINE, '--', 'worker', 'shared', 'config'], { cwd: root, encoding: 'utf8' }).trim().split('\n');
  const objects = execFileSync('git', ['cat-file', '--batch'], { cwd: root, input: names.map((name) => `${BASELINE}:${name}\n`).join(''), maxBuffer: 32 * 1024 * 1024 });
  let offset = 0;
  const sources = [];
  for (const name of names) {
    if (!/^(worker|shared|config)\/[a-zA-Z0-9_./-]+$/u.test(name) || name.includes('..')) throw new Error('Unexpected baseline path.');
    const end = objects.indexOf(10, offset);
    const header = objects.subarray(offset, end).toString('utf8');
    const match = /^[0-9a-f]+ blob (\d+)$/u.exec(header);
    if (!match) throw new Error('Baseline Git object is unavailable.');
    const size = Number(match[1]);
    const bytes = objects.subarray(end + 1, end + 1 + size);
    offset = end + 2 + size;
    sources.push({ name, sha256: hash(bytes) });
    const target = resolve(output, 'src', name);
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, bytes);
  }
  await build({
    entryPoints: [resolve(output, 'src/worker/app.ts')], outfile: resolve(output, 'baseline-app.mjs'),
    bundle: true, packages: 'external', external: ['cloudflare:*', 'node:*'], platform: 'neutral', format: 'esm',
    define: {
      __CANDIDARY_BUILD_SHA__: JSON.stringify(BASELINE),
      __CANDIDARY_MIGRATION_MANIFEST_SHA256__: JSON.stringify('a'.repeat(64)),
      __CANDIDARY_TEST_MEDIA_UPLOAD_RELEASE__: 'true',
    },
  });
  const proof = { baseline: BASELINE, sources, bundleSha256: hash(await readFile(resolve(output, 'baseline-app.mjs'))), lockSha256, builderSha256, esbuildVersion };
  await writeFile(resolve(output, 'provenance.json'), JSON.stringify(proof, null, 2) + '\n');
}

export async function generateMigration() {
  const { DatabaseSync } = await import('node:sqlite');
  const db = new DatabaseSync(':memory:');
  db.exec('PRAGMA foreign_keys = ON');
  const migrations = (await readdir(resolve(root, 'migrations'))).filter((name) => /^00(?:0[1-9]|1\d|2[0-5])_.*\.sql$/u.test(name)).sort();
  if (migrations.length !== 25) throw new Error('Expected exactly the 0001-0025 baseline.');
  for (const file of migrations) db.exec(`BEGIN;\n${await readFile(resolve(root, 'migrations', file), 'utf8')}\nCOMMIT;`);
  const schema = db.prepare("SELECT type, name, tbl_name, sql FROM sqlite_schema WHERE sql IS NOT NULL ORDER BY type, name").all();
  const tables = ['media', 'media_object_promotions'];
  const triggers = schema.filter((row) => row.type === 'trigger' && /\b(?:media|media_object_promotions)\b/u.test(row.sql));
  const indexes = schema.filter((row) => row.type === 'index' && tables.includes(row.tbl_name));
  const columns = Object.fromEntries(tables.map((table) => [table, db.prepare(`PRAGMA table_info(${table})`).all().map((column) => column.name)]));
  if (columns.media.length !== 29 || triggers.length !== 30) throw new Error('Baseline schema drift: review the rebuild before regenerating.');
  const statements = [
    '-- Generated by scripts/build-mobile-image-migration.mjs --generate. Review the explicit SQL before application.',
    `-- Source schema SHA-256: ${hash(JSON.stringify(schema))}. Foreign keys remain enabled.`,
    'PRAGMA defer_foreign_keys = ON;',
    ...tables.map((table) => `CREATE TABLE ${table}_0026_backup AS SELECT * FROM ${table};`),
    ...triggers.map((row) => `DROP TRIGGER ${row.name};`),
    'DROP TABLE media_object_promotions;', 'DROP TABLE media;',
  ];
  for (const table of tables) {
    let sql = schema.find((row) => row.type === 'table' && row.name === table).sql;
    if (table === 'media') sql = sql.replace(/mime_type IN \([\s\S]*?\)/u, "mime_type IN (\n    'image/jpeg', 'image/png', 'image/webp', 'image/heic', 'image/heif',\n    'image/heic-sequence', 'image/heif-sequence', 'image/dng', 'image/avif',\n    'image/avif-sequence', 'image/gif', 'image/tiff', 'image/bmp', 'image/jp2', 'image/jxl'\n  )");
    statements.push(`${sql};`, `INSERT INTO ${table} (${columns[table].join(', ')}) SELECT ${columns[table].join(', ')} FROM ${table}_0026_backup;`, `DROP TABLE ${table}_0026_backup;`);
  }
  statements.push(...indexes.map((row) => `${row.sql};`), ...triggers.map((row) => {
    let sql = row.sql;
    if (row.name === 'media_object_promotion_reservation_capability_guard') {
      // Only a still-owned multipart completion can extend a copying reservation.
      // Legacy buffered writers retain the original pending-only capability.
      sql = sql.replace("AND p.state = 'pending'", `AND (p.state = 'pending' OR (p.state = 'copying'
        AND OLD.upload_state = 'reserved' AND NEW.upload_state = 'reserved'
        AND NEW.object_key = OLD.object_key AND NEW.object_bucket_generation = OLD.object_bucket_generation
        AND p.source_writable_until >= NEW.reservation_expires_at
        AND EXISTS (SELECT 1 FROM media_upload_transfers t JOIN media_upload_assemblies a ON a.transfer_id = t.id
          AND a.attempt = t.attempt AND a.generation = t.generation
          WHERE t.media_id = NEW.id AND t.event_id = NEW.event_id AND t.state = 'processing'
            AND t.completion_token = p.claim_token AND a.completion_token = p.claim_token
            AND a.state = 'completing' AND a.writer_settled_at IS NULL
            AND p.source_etag = 'assembly:' || a.id || ':' || a.expected_sha256
            AND p.source_sha256 = a.expected_sha256 AND p.source_byte_size = a.expected_byte_size
            AND t.expires_at >= NEW.reservation_expires_at AND t.hard_expires_at >= t.expires_at
            AND t.completion_lease_expires_at = p.lease_expires_at)))`);
    }
    if (['media_object_write_tombstone_guard_insert','media_object_write_tombstone_guard_update'].includes(row.name)) {
      // A retired derivative is independently fenced. It must not suppress the
      // original or another derivative of the same media. Exact current object
      // pointer checks remain intact, as do all pre-0026 legacy alias checks.
      sql = sql.replaceAll('(t.event_id = NEW.event_id AND t.media_id = NEW.id)', `(t.event_id = NEW.event_id AND t.media_id = NEW.id
              AND NOT (t.bucket_generation = 'canonical' AND t.object_kind = 'preview'
                AND EXISTS (SELECT 1 FROM media_image_previews p WHERE p.object_key = t.object_key
                  AND p.event_id = t.event_id AND p.media_id = t.media_id AND p.state = 'suppressed')))`);
    }
    return `${sql};`;
  }));
  const catalog = JSON.parse(await readFile(resolve(root, 'shared/mobile-image-cases.json'), 'utf8'));
  const cases = [...new Set([...Object.values(catalog.families).flatMap((family) => [...family.still, ...family.sequence]), ...catalog.paired])].sort();
  const additions = (await readFile(resolve(root, 'scripts/mobile-image-schema.sql'), 'utf8')).replace('-- @ADMISSION_CASES@', `INSERT INTO mobile_image_admission (case_id) VALUES\n${cases.map((id) => `  ('${id}')`).join(',\n')};`);
  statements.push(additions, 'PRAGMA defer_foreign_keys = OFF;');
  const sql = statements.join('\n\n') + '\n';
  db.exec(`BEGIN;\n${sql}\nCOMMIT;`);
  if (db.prepare('PRAGMA foreign_key_check').all().length) throw new Error('Generated migration breaks foreign keys.');
  db.close();
  await writeFile(resolve(root, 'migrations/0026_mobile_image_compatibility.sql'), sql);
}

if (process.argv.includes('--baseline-app')) await prepareBaselineApp();
if (process.argv.includes('--generate')) await generateMigration();
